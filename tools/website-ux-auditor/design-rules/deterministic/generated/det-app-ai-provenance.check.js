/**
 * DET.APP.AI_PROVENANCE — AI suggestion surfaces expose label, provenance, confidence, and accept/reject controls.
 */

export const rule = {
  id: 'DET.APP.AI_PROVENANCE',
  lane: 'deterministic',
  phase: 'metrics',
  area: 'trustAndEcosystemTruth',
  scoreDimension: 'trustAndEcosystemTruth',
  defaultSeverity: 'warn',
  priorityWeight: 8,
  source: 'docs/design/ux-audit/deterministic-design-rules.md#det-app-ai-provenance',
};

/**
 * @param {{ violations?: Array<Record<string, unknown>> } | null | undefined} report
 * @param {string} [url]
 */
export function findingsFromAiProvenanceReport(report, url = '') {
  const violations = Array.isArray(report?.violations) ? report.violations : [];
  if (!violations.length) return [];

  return violations.slice(0, 8).map((v) => ({
    severity: 'warn',
    area: 'trustAndEcosystemTruth',
    message:
      'An AI suggestion surface is missing required provenance controls (label, source, confidence, or accept/reject).',
    evidence: `surface="${String(v.surfaceHint || '')}" missing="${String(v.missing || '')}"`,
    remediation:
      'Compose ForgeAISuggestionReview (Fai) with AI label (Fal), provenance panel (Fpv), confidence indicator (Fci), and revert/accept controls (Fra); satisfy DET.APP.AI_PROVENANCE.',
  })).map((f) => (url ? { ...f, evidence: `${f.evidence} url=${url}` } : f));
}

/** @param {import('playwright').Page} page */
export async function collectAiProvenanceReport(page) {
  return page.evaluate(() => {
    const norm = (s) => String(s || '').replace(/\s+/g, ' ').trim();
    const visible = (el) => {
      if (!el || el.nodeType !== 1) return false;
      const style = window.getComputedStyle(el);
      if (style.display === 'none' || style.visibility === 'hidden') return false;
      const rect = el.getBoundingClientRect();
      return rect.width > 4 && rect.height > 4;
    };

    const labelRe = /AI suggested|Generated by AI/i;
    const actionRe = /accept|reject|revert/i;

    const surfaces = [
      ...document.querySelectorAll(
        '[data-ai-generated], [data-ks-hash="Fai"], .forge-ai-suggestion-review, [data-ai-status]',
      ),
    ].filter(visible);

    /** @type {Array<Record<string, unknown>>} */
    const violations = [];

    for (const surface of surfaces) {
      const scope = surface.closest('[data-ks-hash="Fai"], .forge-ai-suggestion-review') || surface;
      const text = norm(scope.innerText || scope.textContent || '');

      const hasLabel = Boolean(
        scope.querySelector('[data-ai-label], .forge-ai-label, [data-ks-hash="Fal"]')
        || labelRe.test(text),
      );
      const hasProvenance = Boolean(
        scope.querySelector('.forge-provenance-panel, [data-ks-hash="Fpv"], [data-ai-provenance]'),
      );
      const hasConfidence = Boolean(
        scope.querySelector('.forge-confidence-indicator, [data-ks-hash="Fci"], [data-ai-confidence]'),
      );
      const hasAction = Boolean(
        scope.querySelector('.forge-revert-action, [data-ks-hash="Fra"]')
        || [...scope.querySelectorAll('button, a[href], [role="button"]')].some((el) => {
          if (!visible(el)) return false;
          const label = norm(
            el.getAttribute('aria-label') || el.textContent || el.getAttribute('title') || '',
          );
          return actionRe.test(label);
        }),
      );

      const missing = [];
      if (!hasLabel) missing.push('label');
      if (!hasProvenance) missing.push('provenance');
      if (!hasConfidence) missing.push('confidence');
      if (!hasAction) missing.push('accept-reject');

      if (missing.length) {
        const hint = scope.id
          ? `#${scope.id}`
          : scope.getAttribute('data-ks-hash') || 'ai-surface';
        violations.push({
          surfaceHint: hint,
          missing: missing.join(','),
        });
      }
    }

    return { violations: violations.slice(0, 8) };
  });
}

export async function run({ metrics, page, url }) {
  const report = metrics?.aiProvenanceReport
    ?? (page ? await collectAiProvenanceReport(page) : null);
  if (!report?.violations?.length) return [];
  return findingsFromAiProvenanceReport(report, url || metrics?.url || '');
}
